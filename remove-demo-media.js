const admin = require('firebase-admin');
const serviceAccount = require('./final-database-51935-firebase-adminsdk-fbsvc-b6a911c81a.json');

if (!admin.apps.length) {
  admin.initializeApp({
    credential: admin.credential.cert(serviceAccount)
  });
}

const db = admin.firestore();

async function removeAutoGeneratedMedia() {
  try {
    console.log('🔄 Removing auto-generated demo media, keeping only user-uploaded content...\n');
    
    const programsSnapshot = await db.collection('programs').get();
    let updatedCount = 0;

    for (const doc of programsSnapshot.docs) {
      const program = doc.data();
      let programUpdated = false;
      const updates = {};

      console.log(`\n📋 Processing: ${program.title}`);

      // Clean weeklySchedule exercises - remove Unsplash demo images
      if (program.weeklySchedule) {
        const newSchedule = { ...program.weeklySchedule };
        
        for (const [day, dayData] of Object.entries(newSchedule)) {
          if (dayData.exercises && dayData.exercises.length > 0) {
            const cleanedExercises = dayData.exercises.map(ex => {
              const cleaned = { ...ex };
              
              // Remove if it's from Unsplash or YouTube (demo content)
              if (ex.imageUrl && ex.imageUrl.includes('unsplash.com')) {
                delete cleaned.imageUrl;
                delete cleaned.videoUrl;
                delete cleaned.instructions;
                console.log(`  🧹 Removed demo media from: ${ex.name}`);
                updatedCount++;
              }
              
              return cleaned;
            });
            
            newSchedule[day] = {
              ...dayData,
              exercises: cleanedExercises
            };
            programUpdated = true;
          }
        }
        
        if (programUpdated) {
          updates.weeklySchedule = newSchedule;
        }
      }

      // Clean direct exercises
      if (program.exercises && program.exercises.length > 0) {
        const cleanedExercises = program.exercises.map(ex => {
          const cleaned = { ...ex };
          
          if (ex.imageUrl && ex.imageUrl.includes('unsplash.com')) {
            delete cleaned.imageUrl;
            delete cleaned.videoUrl;
            delete cleaned.instructions;
            console.log(`  🧹 Removed demo media from: ${ex.name}`);
            updatedCount++;
          }
          
          return cleaned;
        });
        
        updates.exercises = cleanedExercises;
        programUpdated = true;
      }

      // Clean meals - remove Unsplash demo images
      if (program.meals && program.meals.length > 0) {
        const cleanedMeals = program.meals.map(meal => {
          const cleaned = { ...meal };
          
          if (meal.imageUrl && meal.imageUrl.includes('unsplash.com')) {
            delete cleaned.imageUrl;
            delete cleaned.videoUrl;
            delete cleaned.instructions;
            console.log(`  🧹 Removed demo media from meal: ${meal.name}`);
            updatedCount++;
          }
          
          return cleaned;
        });
        
        updates.meals = cleanedMeals;
        programUpdated = true;
      }

      // Save updates
      if (programUpdated) {
        await doc.ref.update(updates);
        console.log(`  💾 Saved to: ${program.title}`);
      }
    }

    console.log('\n' + '='.repeat(60));
    console.log(`✅ Complete!`);
    console.log(`🧹 Removed demo media from: ${updatedCount} items`);
    console.log('📌 Now only user-uploaded content will be shown');
    console.log('='.repeat(60));

    process.exit(0);
  } catch (error) {
    console.error('❌ Error:', error);
    process.exit(1);
  }
}

removeAutoGeneratedMedia();
