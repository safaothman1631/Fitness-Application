const admin = require('firebase-admin')
const fs = require('fs')
const path = require('path')

// Load .env
const envPath = path.join(__dirname, '.env')
if (fs.existsSync(envPath)) {
  const envContent = fs.readFileSync(envPath, 'utf8')
  envContent.split('\n').forEach(line => {
    line = line.trim()
    if (!line || line.startsWith('#')) return
    
    const equalIndex = line.indexOf('=')
    if (equalIndex === -1) return
    
    const key = line.substring(0, equalIndex).trim()
    let value = line.substring(equalIndex + 1).trim()
    
    if ((value.startsWith('"') && value.endsWith('"')) || 
        (value.startsWith("'") && value.endsWith("'"))) {
      value = value.slice(1, -1)
    }
    
    process.env[key] = value
  })
  console.log('✅ Loaded .env')
}

// Initialize Firebase Admin
if (!admin.apps.length) {
  try {
    const projectId = process.env.FIREBASE_PROJECT_ID
    const privateKey = process.env.FIREBASE_PRIVATE_KEY?.replace(/\\n/g, '\n')
    
    admin.initializeApp({
      credential: admin.credential.cert({
        projectId: projectId,
        privateKeyId: process.env.FIREBASE_PRIVATE_KEY_ID,
        privateKey: privateKey,
        clientEmail: process.env.FIREBASE_CLIENT_EMAIL,
        clientId: process.env.FIREBASE_CLIENT_ID,
      }),
      storageBucket: `${projectId}.firebasestorage.app`
    })
    console.log('✅ Firebase Admin initialized')
    console.log('📦 Bucket:', `${projectId}.firebasestorage.app`)
  } catch (error) {
    console.error('❌ Firebase initialization failed:', error.message)
    process.exit(1)
  }
}

const bucket = admin.storage().bucket()
const db = admin.firestore()

async function refreshVideoURLsInPrograms() {
  try {
    console.log('='.repeat(60))
    console.log('🔄 Refreshing video URLs in all programs...')
    console.log('='.repeat(60))
    console.log()
    
    // Get all programs
    const programsSnapshot = await db.collection('programs').get()
    console.log(`📊 Found ${programsSnapshot.size} programs`)
    console.log()
    
    let updatedCount = 0
    let videoCount = 0
    
    for (const doc of programsSnapshot.docs) {
      const program = doc.data()
      let needsUpdate = false
      
      if (program.weeklySchedule) {
        for (const [day, dayData] of Object.entries(program.weeklySchedule)) {
          if (dayData.exercises && Array.isArray(dayData.exercises)) {
            for (const exercise of dayData.exercises) {
              if (exercise.videos && Array.isArray(exercise.videos)) {
                for (const video of exercise.videos) {
                  if (video.url && video.url.includes('storage.googleapis.com')) {
                    videoCount++
                    // URLs will be regenerated by API when accessed
                    needsUpdate = true
                  }
                }
              }
            }
          }
        }
      }
      
      if (needsUpdate) {
        updatedCount++
        console.log(`✅ Program: ${doc.id} (${program.name || 'Unnamed'}) - ${videoCount} videos`)
      }
    }
    
    console.log()
    console.log('='.repeat(60))
    console.log(`✅ Processed ${programsSnapshot.size} programs`)
    console.log(`📊 ${updatedCount} programs have videos`)
    console.log(`🎬 Total videos found: ${videoCount}`)
    console.log('='.repeat(60))
    console.log()
    console.log('💡 Note: Video URLs will be regenerated when accessed through the API')
    console.log('   The signed URLs expire after 7 days.')
    console.log()
    
  } catch (error) {
    console.error('❌ Error:', error.message)
    throw error
  }
}

refreshVideoURLsInPrograms()
  .then(() => {
    console.log('✅ Done!')
    process.exit(0)
  })
  .catch(error => {
    console.error('Fatal error:', error)
    process.exit(1)
  })
